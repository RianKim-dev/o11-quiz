// Generates (1) a lightweight manifest of the question bank for the dashboard, and
// (2) an auto-wired loader (src/generated/all-questions.ts) importing every content
// file — so adding a new content/questions/*.json needs no manual import.
// Only status==="verified" questions are counted/served; "flagged" are excluded.
// Runs on predev / prebuild; also `npm run gen`.

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const qDir = join(root, "content", "questions");
const outDir = join(root, "src", "generated");

const files = (await readdir(qDir)).filter((f) => f.endsWith(".json")).sort();

/** @type {Record<string, { category: string, count: number }>} */
const subtopics = {};
let total = 0;
let flagged = 0;
const ids = new Set();

for (const f of files) {
  const arr = JSON.parse(await readFile(join(qDir, f), "utf8"));
  for (const q of arr) {
    if (ids.has(q.id)) throw new Error(`Duplicate question id: ${q.id} (in ${f})`);
    ids.add(q.id);
    if (q.status !== "verified") {
      flagged += 1;
      continue;
    }
    total += 1;
    const s = (subtopics[q.subtopic] ??= { category: q.category, count: 0 });
    s.count += 1;
  }
}

await mkdir(outDir, { recursive: true });
await writeFile(
  join(outDir, "manifest.json"),
  JSON.stringify({ total, subtopics }, null, 2) + "\n"
);

// Auto-wired loader: import every content file, export the raw combined array.
const importLines = files.map((f, i) => `import f${i} from "@content/questions/${f}";`).join("\n");
const spreadLines = files.map((_, i) => `  ...(f${i} as unknown as Question[]),`).join("\n");
const loader =
  `// AUTO-GENERATED by scripts/gen-manifest.mjs — do not edit by hand.\n` +
  `import type { Question } from "@/types/question";\n${importLines}\n\n` +
  `export const RAW_QUESTIONS: Question[] = [\n${spreadLines}\n];\n`;
await writeFile(join(outDir, "all-questions.ts"), loader);

console.log(
  `✓ ${total} verified questions across ${Object.keys(subtopics).length} subtopics (${files.length} files)` +
    (flagged ? ` · ${flagged} flagged (excluded)` : "")
);
